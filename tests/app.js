    await tbi.evaluate(async () => { await Banc.Donnees.importe({ students: [{ id: "a", name: "Test V1", goal: "60" }], results: [{ sid: "a", ep: "E1", date: "2026-10-10T10:00:00.000Z", essai: 1, mclm: 48, read: 50, err: 2, secs: 60 }], speed: 0.8 }); });
