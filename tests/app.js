    await attends(() => tbi.evaluate(() => !document.querySelector("#audio").paused), 6000, "voix lancée à distance");
    await attends(() => tel.evaluate(() => /lecture en cours/.test(document.querySelector("#t-main").textContent)), 6000, "état « lecture »");
