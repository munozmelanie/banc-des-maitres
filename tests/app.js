    tbi = await ouvre(ctxE2, base + Q + "#ecran&lien=" + code);
    await attends(() => tbi.evaluate(() => Banc.Donnees.essais().length === 2 && Banc.Donnees.eleves()[1].nom === "Test B"), 15000, "récupération");
